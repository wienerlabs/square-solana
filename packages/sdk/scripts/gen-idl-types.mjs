#!/usr/bin/env node
// idl/*.json → src/idl/<program>.json (kopya) + src/idl/<program>.ts (Anchor'ın camelCase TS tipi).
// Anchor CLI'ın (1.2.0, `anchor idl type`) ürettiği tip dosyasıyla aynı dönüşümü yapar: `name`,
// `relations` ve `account` değerleri lowerCamelCase olur; `path`'in her nokta parçası ayrı çevrilir
// (ör. `release_proof.job` → `releaseProof.job`).
//   node scripts/gen-idl-types.mjs          dosyaları yazar
//   node scripts/gen-idl-types.mjs --check  dosyalar güncel değilse 1 ile çıkar
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../..');
const outDir = resolve(here, '../src/idl');
const PROGRAMS = ['registry', 'policy', 'verifier', 'escrow'];

// heck::ToLowerCamelCase ile aynı sözcük bölme: `_`, küçük→büyük geçişi ve kısaltma sınırları.
function words(s) {
  return s.split('_').flatMap((part) => part.match(/[A-Z]+(?=[A-Z][a-z0-9])|[A-Z]?[a-z0-9]+|[A-Z]+/g) ?? []);
}
function lowerCamel(s) {
  return words(s)
    .map((w, i) => (i === 0 ? w.toLowerCase() : w.charAt(0).toUpperCase() + w.slice(1).toLowerCase()))
    .join('');
}
function upperCamel(s) {
  const c = lowerCamel(s);
  return c.charAt(0).toUpperCase() + c.slice(1);
}

function convert(value, key) {
  if (Array.isArray(value)) return value.map((v) => convert(v, key));
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, convert(v, k)]));
  }
  if (typeof value !== 'string') return value;
  if (key === 'name' || key === 'relations' || key === 'account') return lowerCamel(value);
  if (key === 'path') return value.split('.').map(lowerCamel).join('.');
  return value;
}

function render(program) {
  const file = `square_${program}_contract`;
  const jsonText = readFileSync(resolve(root, `idl/${file}.json`), 'utf8');
  const idl = JSON.parse(jsonText);
  const typeName = upperCamel(idl.metadata.name);
  const ts = [
    '/**',
    ' * Program IDL in camelCase format in order to be used in JS/TS.',
    ' *',
    ' * Note that this is only a type helper and is not the actual IDL. The original',
    ` * IDL can be found at \`idl/${file}.json\` (generated by packages/sdk/scripts/gen-idl-types.mjs).`,
    ' */',
    `export type ${typeName} = ${JSON.stringify(convert(idl, null), null, 2)};`,
    '',
  ].join('\n');
  return [
    [resolve(outDir, `${file}.json`), jsonText],
    [resolve(outDir, `${file}.ts`), ts],
  ];
}

const files = PROGRAMS.flatMap(render);
if (process.argv.includes('--check')) {
  const read = (p) => {
    try {
      return readFileSync(p, 'utf8');
    } catch {
      return null;
    }
  };
  const stale = files.filter(([p, text]) => read(p) !== text).map(([p]) => p.replace(`${root}/`, ''));
  if (stale.length) {
    for (const p of stale) console.error(`güncel değil: ${p} (pnpm --filter @squaresdk/solana-sdk gen)`);
    process.exit(1);
  }
  console.log('SDK IDL tipleri güncel.');
} else {
  mkdirSync(outDir, { recursive: true });
  for (const [p, text] of files) writeFileSync(p, text);
  console.log('SDK IDL tipleri yazıldı.');
}
